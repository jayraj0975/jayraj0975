const GENERATED_HEADER = [
  /Code generated .* DO NOT EDIT\.?/,
  /@generated\b/,
  /\bDO NOT EDIT\b.*\b(generated|autogenerated)\b/i,
  /\b(auto-?generated|automatically generated|machine generated) (file|code|by)\b/i,
  /This file (was|is) (auto(matically)?[- ]?)?generated/i,
  /Generated by the protocol buffer compiler/,
  /Autogenerated by Thrift/,
  /generated by (?:swagger|openapi)-codegen/i,
  /<auto-generated\s*\/?>/i,
];

/** Marker text if the first lines of a file declare it generated. */
export function generatedHeaderMarker(text: string): string | null {
  const head = text.slice(0, 2048).split('\n').slice(0, 12);
  for (const line of head) {
    // "Generated by ChatGPT/Claude/Copilot" is a statement about AI authorship, not tool-generated code.
    if (/\b(chatgpt|gpt-?\d|claude|copilot|gemini|cursor|devin|codex|an? ai\b|ai assistant|llm)\b/i.test(line)) continue;
    for (const re of GENERATED_HEADER) {
      const m = re.exec(line);
      if (m) return m[0];
    }
  }
  return null;
}

/** Minified JS/CSS: few very long lines. */
export function looksMinified(path: string, text: string): boolean {
  const e = extname(path);
  if (!['.js', '.mjs', '.cjs', '.css'].includes(e) || text.length < 2048) return false;
  const lines = text.split('\n');
  const longLines = lines.filter((l) => l.length > 1000).length;
  return longLines > 0 && text.length / Math.max(lines.length, 1) > 300;
}

