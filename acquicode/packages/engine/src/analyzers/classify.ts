const VENDOR_SEGMENTS = new Set(['vendor', 'vendored', 'third_party', 'third-party', 'thirdparty', 'node_modules', 'bower_components', 'Pods']);

/** Root directory of vendored code containing this path, if any. */
export function vendoredRoot(path: string): string | null {
  const segs = segments(path);
  for (let i = 0; i < segs.length - 1; i++) {
    if (VENDOR_SEGMENTS.has(segs[i]!)) return segs.slice(0, i + 1).join('/');
    if (segs[i] === 'Carthage' && segs[i + 1] === 'Checkouts') return segs.slice(0, i + 2).join('/');
  }
  return null;
}

const BUILD_OUTPUT_DIRS = new Set(['dist', 'build', 'out', '.next', '.nuxt', 'target', 'obj', 'coverage', '__pycache__', '.svelte-kit', '.output']);

export function buildOutputDir(path: string): string | null {
  const segs = segments(path);
  for (let i = 0; i < segs.length - 1; i++) if (BUILD_OUTPUT_DIRS.has(segs[i]!)) return segs.slice(0, i + 1).join('/');
  return null;
}

