export function binaryKindByMagic(head: Uint8Array): BinaryKind | null {
  if (head.length >= 4 && head[0] === 0x7f && head[1] === 0x45 && head[2] === 0x4c && head[3] === 0x46) return 'executable'; // ELF
  if (head.length >= 2 && head[0] === 0x4d && head[1] === 0x5a) return 'executable'; // PE "MZ"
  if (head.length >= 4) {
    const m = ((head[0]! << 24) | (head[1]! << 16) | (head[2]! << 8) | head[3]!) >>> 0;
    if ([0xfeedface, 0xfeedfacf, 0xcefaedfe, 0xcffaedfe, 0xcafebabe].includes(m)) return m === 0xcafebabe ? 'bytecode' : 'executable';
  }
  if (head.length >= 4 && head[0] === 0x50 && head[1] === 0x4b && head[2] === 0x03 && head[3] === 0x04) return 'archive';
  if (head.length >= 4 && head[0] === 0x00 && head[1] === 0x61 && head[2] === 0x73 && head[3] === 0x6d) return 'bytecode'; // wasm
  return null;
}

