const CODE_LANGS = new Set(
  Object.values(LANGUAGES).filter((l) => !['YAML', 'JSON', 'TOML', 'XML', 'Markdown', 'MDX', 'reStructuredText'].includes(l)),
);

export function languageOf(path: string): string | undefined {
  const b = basename(path);
  if (b === 'Dockerfile' || b.startsWith('Dockerfile.') || b.endsWith('.dockerfile')) return 'Dockerfile';
  if (b === 'Makefile' || b === 'makefile' || b === 'GNUmakefile') return 'Makefile';
  return LANGUAGES[extname(path)];
}

export function isCodeLanguage(lang: string | undefined): boolean {
  return !!lang && (CODE_LANGS.has(lang) || lang === 'Dockerfile' || lang === 'Makefile');
}

