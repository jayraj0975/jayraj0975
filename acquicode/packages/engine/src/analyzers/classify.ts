export interface Gitattributes {
  generated: RegExp[];
  vendored: RegExp[];
  documentation: RegExp[];
  notGenerated: RegExp[];
}

export function parseGitattributes(text: string): Gitattributes {
  const out: Gitattributes = { generated: [], vendored: [], documentation: [], notGenerated: [] };
  for (const raw of text.split('\n')) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const [pattern, ...attrs] = line.split(/\s+/);
    if (!pattern) continue;
    const re = globToRegExp(normalizePath(pattern));
    for (const a of attrs) {
      if (a === 'linguist-generated' || a === 'linguist-generated=true') out.generated.push(re);
      else if (a === '-linguist-generated' || a === 'linguist-generated=false') out.notGenerated.push(re);
      else if (a === 'linguist-vendored' || a === 'linguist-vendored=true') out.vendored.push(re);
      else if (a === 'linguist-documentation' || a === 'linguist-documentation=true') out.documentation.push(re);
    }
  }
  return out;
}

export function baseClasses(path: string): FileClass[] {
  const classes = new Set<FileClass>();
  if (isLockfile(path)) classes.add('lockfile');
  else if (isManifest(path)) classes.add('manifest');
  if (vendoredRoot(path)) classes.add('vendored');
  if (generatedByName(path) || buildOutputDir(path)) classes.add('generated');
  const lang = languageOf(path);
  if (isTestPath(path)) classes.add('test');
  if (isCodeLanguage(lang) && !classes.has('test')) classes.add('source');
  if (!classes.size) {
    if (isDocsPath(path)) classes.add('docs');
    else if (CONFIG_EXT.has(extname(path)) || basename(path).startsWith('.')) classes.add('config');
  }
  return [...classes];
}
